@requires_real_data
def test_dashboard_uses_the_derived_revenue_metric(real_session: DataSession) -> None:
    """The real retail table has quantity and price but no revenue column.

    A dashboard headlining 'total quantity' would be misleading, so the measure
    expression must be the product and it must be disclosed in the notes.
    """
    dash = build_dashboard(real_session, RETAIL)
    assert dash.measure_expression == "quantity * price"
    assert any("computed as" in n for n in dash.notes)
    labels = [k.label.lower() for k in dash.kpis]
    assert any("revenue" in label for label in labels)


@requires_real_data
def test_dashboard_kpis_are_populated(real_session: DataSession) -> None:
    dash = build_dashboard(real_session, RETAIL)
    assert len(dash.kpis) >= 4
    rows = next(k for k in dash.kpis if k.label == "Rows")
    assert rows.value == "86,041"
    period = next(k for k in dash.kpis if k.label == "Period")
    assert period.value.startswith("2009-12")


@requires_real_data
def test_dashboard_panels_render_and_carry_their_sql(real_session: DataSession) -> None:
    dash = build_dashboard(real_session, RETAIL)
    assert len(dash.panels) >= 3

    kinds = {p.spec.type.value for p in dash.panels}
    assert "line" in kinds, "a dated table should produce a trend panel"
    assert "horizontal_bar" in kinds, "dimensions should produce ranking panels"

    for panel in dash.panels:
        assert panel.sql.lower().startswith("select")
        assert panel.rows, f"panel '{panel.title}' returned no rows"
        frame = pd.DataFrame(panel.rows, columns=panel.columns)
        # Must actually render, not merely hold data.
        assert build_figure(panel.spec, frame).data


@requires_real_data
def test_dashboard_panel_sql_passes_the_guard(real_session: DataSession) -> None:
    """Dashboard SQL is generated by our own code, but it goes through the same
    guard as model-generated SQL — no bypass path exists."""
    dash = build_dashboard(real_session, RETAIL)
    for panel in dash.panels:
        result, guard = real_session.execute_sql(panel.sql)
        assert guard.tables == [RETAIL]
        assert result.row_count >= 0


@requires_real_data
def test_dashboard_trend_matches_the_ground_truth(real_session: DataSession) -> None:
    from evals.ground_truth import monthly_revenue

    truth = monthly_revenue()
    dash = build_dashboard(real_session, RETAIL)
    trend = next(p for p in dash.panels if p.spec.type.value == "line")
    frame = pd.DataFrame(trend.rows, columns=trend.columns)
    assert len(frame) == truth.value["periods"]
    best = frame.loc[frame[trend.spec.y].idxmax()]
    assert best["month"] == truth.value["best_period"]
    assert best[trend.spec.y] == pytest.approx(truth.value["best_value"], rel=1e-6)


