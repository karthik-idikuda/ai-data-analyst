@requires_real_data
def test_excel_export_is_a_valid_multi_sheet_workbook(real_session: DataSession) -> None:
    payload = to_excel(real_session)
    assert payload[:2] == b"PK", "xlsx is a zip archive"

    book = pd.ExcelFile(io.BytesIO(payload), engine="openpyxl")
    assert "Overview" in book.sheet_names
    assert any(name.startswith("schema_") for name in book.sheet_names)

    overview = book.parse("Overview")
    assert set(overview["table"]) == set(real_session.table_names)
    assert int(overview.loc[overview["table"] == RETAIL, "rows"].iloc[0]) == 86_041

    schema = book.parse(next(n for n in book.sheet_names if n.startswith("schema_")))
    assert {"column", "type", "role", "null_pct"} <= set(schema.columns)


@requires_real_data
def test_excel_sheet_names_stay_within_excel_limits(real_session: DataSession) -> None:
    book = pd.ExcelFile(io.BytesIO(to_excel(real_session)), engine="openpyxl")
    for name in book.sheet_names:
        assert len(name) <= 31, f"'{name}' exceeds Excel's 31-character sheet-name limit"
        assert not set(name) & set("[]:*?/\\")
    assert len(set(n.lower() for n in book.sheet_names)) == len(book.sheet_names)


@requires_real_data
def test_excel_includes_conversation_artifacts(fake_provider_factory) -> None:
    from core.agent import Agent
    from tests.conftest import ScriptedTurn

    from tests.conftest import RETAIL_CSV

    # A fresh session so the exported conversation contains exactly one turn.
    session = DataSession()
    session.add_csv_path(RETAIL_CSV)
    try:
        provider = fake_provider_factory(
            [
                ScriptedTurn(tool_calls=[("run_sql", {
                    "sql": f"SELECT country, SUM(quantity*price) AS revenue FROM {RETAIL} "
                           f"GROUP BY 1 ORDER BY 2 DESC LIMIT 5",
                    "purpose": "revenue by country",
                })]),
                ScriptedTurn(text="EIRE leads."),
            ]
        )
        Agent(provider).answer(session, "Which country generated the highest revenue?")

        book = pd.ExcelFile(io.BytesIO(to_excel(session)), engine="openpyxl")
        assert "SQL executed" in book.sheet_names
        result_sheets = [n for n in book.sheet_names if n.startswith("Q1_")]
        assert result_sheets, "the query result should be exported as its own sheet"
        frame = book.parse(result_sheets[0])
        assert len(frame) == 5
        assert "revenue" in [c.lower() for c in frame.columns]
    finally:
        session.close()


